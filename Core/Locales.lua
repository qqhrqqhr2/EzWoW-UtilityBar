function ns:GetActiveLang()
    local lang = (self.db and self.db.language) or (_G.EzWoW_UtilityBarDB and _G.EzWoW_UtilityBarDB.language) or "auto"
    if lang == "auto" then
        lang = (type(GetLocale) == "function" and GetLocale()) or "enUS"
    end
    if lang == "esMX" then lang = "esES" end
    if lang == "enGB" then lang = "enUS" end
    return UI_STRINGS[lang] and lang or "enUS"
end

function ns:L(key)
    local lang = self:GetActiveLang()
    local tbl = UI_STRINGS[lang] or UI_STRINGS.enUS
    return tbl[key] or UI_STRINGS.enUS[key] or key
end

function ns:GetGroupLabel(groupKey)
    local lang = self:GetActiveLang()
    local tbl = GROUP_NAMES[lang] or GROUP_NAMES.enUS
    return tbl[groupKey] or GROUP_NAMES.enUS[groupKey] or groupKey
end

function ns:GetLanguageDisplayLabel()
    local pref = (self.db and self.db.language) or "auto"
    for _, item in ipairs(self.LANGUAGE_OPTIONS) do
        if item[1] == pref then
            return item[2]
        end
    end
    return "Auto"
end

